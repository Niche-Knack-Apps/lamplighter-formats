#!/usr/bin/env python3
"""Build lib/versification-data.js from SIL's versification tables in data/versification/.

The output keeps each mapping line as written (ranges expand at first use) and, for detection,
only the chapter and verse counts that differ between schemes. Run after updating the tables;
--check fails when the committed output is stale.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "data/versification"
OUTPUT = ROOT / "lib/versification-data.js"
SCHEMES = {"eng": "English", "org": "Original", "vul": "Vulgate"}
SOURCE = {
    "repository": "https://github.com/sillsdev/libpalaso",
    "path": "SIL.Scripture/Resources",
    "commit": "b4f7a6da7b868f9ae909e40fb0708f5fd4efd782",
    "license": "MIT, Copyright (c) 2007-2026 SIL Global",
}
BOOK_LINE = re.compile(r"^([0-9A-Z]{3})((?: \d+:\d+)+)$")
MAPPING = re.compile(r"^([0-9A-Z]{3}) (\d+):(\d+)(?:-(\d+))? = ([0-9A-Z]{3}) (\d+):(\d+)(?:-(\d+))?$")


def read_table(path):
    counts, mappings, skipped = {}, [], []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if "=" in line:
            match = MAPPING.match(line)
            # Half-verse segments (1:1a) and backwards ranges cannot be mapped verse to verse.
            if not match or int(match[4] or match[3]) < int(match[3]) or int(match[8] or match[7]) < int(match[7]):
                skipped.append(line)
                continue
            mappings.append(f"{match[1]} {match[2]}:{match[3]}{'-' + match[4] if match[4] else ''}="
                            f"{match[5]} {match[6]}:{match[7]}{'-' + match[8] if match[8] else ''}")
        elif BOOK_LINE.match(line):
            book, rest = line.split(" ", 1)
            pairs = [tuple(int(n) for n in pair.split(":")) for pair in rest.split()]
            if [chapter for chapter, _ in pairs] != list(range(1, len(pairs) + 1)):
                skipped.append(line)  # chapters listed out of sequence (vul 6EZ)
                continue
            counts[book] = [verses for _, verses in pairs]
        elif not line.startswith(("-", "*", "&")):
            raise SystemExit(f"{path.name}: unrecognized line: {raw!r}")
    return counts, mappings, skipped


def fingerprint(tables):
    """Counts that tell the schemes apart: [book, chapter, {scheme: count}]; chapter 0 is the chapter count."""
    items = []
    books = sorted({book for counts, _, _ in tables.values() for book in counts})
    for book in books:
        have = {scheme: table[0][book] for scheme, table in tables.items() if book in table[0]}
        if len(have) < 2:
            continue
        chapter_counts = {scheme: len(chapters) for scheme, chapters in have.items()}
        if len(set(chapter_counts.values())) > 1:
            items.append([book, 0, chapter_counts])
        for chapter in range(1, max(chapter_counts.values()) + 1):
            verse_counts = {scheme: chapters[chapter - 1] for scheme, chapters in have.items() if chapter <= len(chapters)}
            if len(verse_counts) > 1 and len(set(verse_counts.values())) > 1:
                items.append([book, chapter, verse_counts])
    return items


def build():
    tables, files = {}, {}
    for scheme in SCHEMES:
        path = TABLES / f"{scheme}.vrs.txt"
        files[path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
        tables[scheme] = read_table(path)
    data = {
        "source": {**SOURCE, "files": files},
        "schemes": {scheme: {"name": name, "toOriginal": tables[scheme][1]} for scheme, name in SCHEMES.items()},
        "fingerprint": fingerprint(tables),
    }
    body = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    text = (
        "// Generated by scripts/build-versification.py from SIL's versification tables (MIT, see NOTICE).\n"
        "// Do not edit by hand.\n"
        "(function (root) {\n"
        f"  var data = {body};\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
        "  else root.VERSIFICATION_DATA = data;\n"
        "}(typeof window !== 'undefined' ? window : this));\n"
    )
    skipped = {scheme: len(table[2]) for scheme, table in tables.items()}
    return text, skipped, len(data["fingerprint"])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if lib/versification-data.js is out of date")
    args = parser.parse_args()
    text, skipped, items = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            sys.exit("lib/versification-data.js is out of date; run scripts/build-versification.py")
        return
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(text.encode())} bytes, {items} fingerprint counts; "
          f"skipped lines: {', '.join(f'{k} {v}' for k, v in skipped.items())})")


if __name__ == "__main__":
    main()
